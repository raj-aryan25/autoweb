"""Generate transport types and compile-checked fixtures from the Python schema.

Run with conda run -n autoweb python scripts/generate_studio_contracts.py [--check].
"""

import argparse
import json
from pathlib import Path

from pydantic import TypeAdapter

from autoweb_api.contracts import ContractScenario, ProfileDescriptor, StartRun
from autoweb_api.api_contracts import PreflightRequest, PreflightResult, RunRecord, RunPage

ROOT = Path(__file__).resolve().parents[1]


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(ts_type(item) for item in schema[key])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    kind = schema.get("type")
    if kind == "object":
        required = schema.get("required", [])
        fields = [f'{json.dumps(name)}{"" if name in required else "?"}: {ts_type(value)};'
                  for name, value in schema.get("properties", {}).items()]
        return "{ " + " ".join(fields) + " }"
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind in {"integer", "number"}:
        return "number"
    if kind in {"string", "boolean", "null"}:
        return kind
    raise ValueError(f"Unsupported schema: {schema}")


def outputs():
    adapter = TypeAdapter(tuple[ContractScenario, ProfileDescriptor, StartRun, PreflightRequest, PreflightResult, RunRecord, RunPage])
    schema = adapter.json_schema()
    definitions = schema.pop("$defs")
    types = "// Generated by scripts/generate_studio_contracts.py; do not edit.\n"
    types += "// Python validates bounds, identifiers, timestamps and cross-field rules.\n"
    types += "\n".join(f"export type {name} = {ts_type(value)};" for name, value in sorted(definitions.items())) + "\n"
    scenarios = json.loads((ROOT / "tests/fixtures/studio/contracts.json").read_text())
    for scenario in scenarios:
        ContractScenario.model_validate(scenario)
    fixtures = '// Generated from tests/fixtures/studio/contracts.json; do not edit.\n'
    fixtures += 'import type { ContractScenario } from "./contracts";\n'
    fixtures += 'export const contractFixtures = ' + json.dumps(scenarios, indent=2) + ' satisfies ContractScenario[];\n'
    return {
        ROOT / "apps/web/src/transport/contracts.ts": types,
        ROOT / "apps/web/src/transport/contractFixtures.ts": fixtures,
        ROOT / "docs/contracts/studio-v1.schema.json": json.dumps({"$defs": definitions, **schema}, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale Studio contract: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
